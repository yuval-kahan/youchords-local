function normalizeAiMode(rawMode) {
  const mode = typeof rawMode === 'string' ? rawMode.toLowerCase() : 'off';
  return mode === 'auto' || mode === 'always' ? mode : 'off';
}

function stableStringify(value) {
  if (value === null || typeof value !== 'object') {
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) {
    return `[${value.map(stableStringify).join(',')}]`;
  }
  const keys = Object.keys(value).sort();
  return `{${keys.map((key) => `${JSON.stringify(key)}:${stableStringify(value[key])}`).join(',')}}`;
}

function stripNoCaptionsMarker(data) {
  if (!data || typeof data !== 'object') return data;
  if (data.hasSubtitles !== false && data.error !== 'NO_CAPTIONS') return data;

  const { hasSubtitles, checkedAt, error, ...rest } = data;
  return rest;
}

function hasGeminiTranscriptionRuntime() {
  return (
    typeof window.fetchGeminiTranscriptionWithLoadBalancing === 'function' ||
    typeof window.fetchGeminiTranscriptionWithFallback === 'function' ||
    typeof window.fetchGeminiTranscription === 'function'
  );
}

async function ensureGeminiTranscriptionRuntime() {
  if (hasGeminiTranscriptionRuntime()) return true;

  try {
    await import(chrome.runtime.getURL('utils/geminiTranscription.js'));
  } catch (error) {
    console.error('[YouTubeSubs] Gemini module failed to load:', error);
  }

  return hasGeminiTranscriptionRuntime();
}

