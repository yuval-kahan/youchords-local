/**
 * Convert Gemini subtitles format to internal format
 * Gemini returns: [{start, end, text}]
 * We need: words array + sentence SRT
 */
function convertGeminiToInternalFormat(geminiSubtitles) {
  if (!geminiSubtitles || geminiSubtitles.length === 0) {
    return { words: [], sentenceSRT: '', wordSRT: null, originalSentences: [] };
  }

  if (DEBUG_YOUTUBE_SUBS) {
    console.log('[YouTubeSubs] 🔄 Converting Gemini format...');
    console.log('[YouTubeSubs] 🔥🔥🔥 GEMINI INPUT TO CONVERT 🔥🔥🔥');
    console.log(JSON.stringify(geminiSubtitles, null, 2));
    console.log('[YouTubeSubs] 🔥🔥🔥 END GEMINI INPUT 🔥🔥🔥');
  }

  // Create sentence SRT directly from Gemini output
  let sentenceSRT = '';
  const originalSentences = [];

  geminiSubtitles.forEach((sub, index) => {
    const cleanText = cleanPunctuationSpacing(sub.text);
    sentenceSRT += `${index + 1}\n${formatTime(sub.start)} --> ${formatTime(sub.end)}\n${cleanText}\n\n`;

    // 🎯 Create words array for highlighting
    const words = [];
    const textWords = sub.text.split(/\s+/).filter(w => w.length > 0);
    const duration = sub.end - sub.start;
    const wordDuration = duration / textWords.length;
    
    textWords.forEach((word, wordIndex) => {
      const wordStart = sub.start + (wordIndex * wordDuration);
      const wordEnd = sub.start + ((wordIndex + 1) * wordDuration);
      
      words.push({
        word: word,
        start: Math.round(wordStart * 100) / 100,  // ✅ Round to 2 decimals
        end: Math.round(wordEnd * 100) / 100       // ✅ Round to 2 decimals
      });
    });

    // 🎯 ללא הפחתה - משתמשים בזמנים המקוריים מ-Gemini
    originalSentences.push({
      text: sub.text,
      startTime: sub.start,
      endTime: sub.end,  // ✅ זמן מקורי ללא שינוי
      words: words  // 🆕 מילים עם timestamps משוערכים להדגשה!
    });
  });

  if (DEBUG_YOUTUBE_SUBS) {
    console.log('[YouTubeSubs] ✅ Conversion complete');
    console.log('[YouTubeSubs] 🔥🔥🔥 ORIGINAL SENTENCES CREATED 🔥🔥🔥');
    console.log(JSON.stringify(originalSentences, null, 2));
    console.log('[YouTubeSubs] 🔥🔥🔥 END ORIGINAL SENTENCES 🔥🔥🔥');
  }

  // Gemini doesn't provide word-level timing, so wordSRT is null
  // words array is empty (no word-level data)
  return {
    words: [],
    sentenceSRT,
    wordSRT: null,
    originalSentences,
    hasWordLevel: false
  };
}

/**
 * Determine error type from error message for modal display
 */
function determineGeminiErrorType(errorMessage) {
  if (!errorMessage) return 'generic';

  const msg = errorMessage.toLowerCase();

  if (msg.includes('rate limit')) return '429';
  if (msg.includes('quota exceeded') || msg.includes('quota')) return '403-quota';
  if (msg.includes('invalid api key') || msg.includes('permission denied')) return '403-key';
  if (msg.includes('bad request') || msg.includes('invalid request')) return '400';
  if (msg.includes('timeout') || msg.includes('timed out')) return 'timeout';
  if (msg.includes('no transcription') || msg.includes('empty response')) return 'empty';
  if (msg.includes('network') || msg.includes('connection')) return 'network';

  return 'generic';
}

/**
 * Try to fetch subtitles from Gemini AI
 * @param {string} videoId - YouTube video ID
 * @param {string} forcePromptType - Force specific prompt type: 'default', 'custom', 'translation', or null
 * @param {string} translationLanguage - Language code for translation (only used when forcePromptType === 'translation')
 * @param {number} preferredKeyIndex - Preferred key index for load balancing (optional)
 * Returns null if failed or not configured
 */
async function tryGeminiTranscription(videoId, forcePromptType = null, translationLanguage = null, preferredKeyIndex = null) {
  try {
    const aiSettings = await chrome.storage.local.get(['aiTranscriptionMode', PROMPT_DISCLAIMER_KEY]);
    const aiMode = aiSettings.aiTranscriptionMode || 'off';
    if (aiMode === 'off') {
      if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] 🤖 Gemini blocked: aiTranscriptionMode=off');
      return null;
    }

    if (aiSettings[PROMPT_DISCLAIMER_KEY] !== true) {
      if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] 🤖 Gemini blocked: prompt responsibility not accepted');
      showPromptResponsibilityRequired();
      return null;
    }

    // Long-video Gemini notice is shown inside the Gemini progress bar.

    // Read settings - check if we have any API key configured
    const settings = await new Promise((resolve) => {
      chrome.storage.local.get(['geminiApiKey', 'geminiApiKeys'], (result) => {
        resolve(result);
      });
    });

    const hasSingleKey = !!settings.geminiApiKey;
    const hasMultiKeys = hasActiveGeminiMultiKey(settings.geminiApiKeys);

    if (!hasSingleKey && !hasMultiKeys) {
      if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] 🤖 Gemini: No API key configured');
      return null;
    }

    await ensureGeminiTranscriptionRuntime();

    // Check if Gemini modules are loaded
    const hasLoadBalancing = typeof window.fetchGeminiTranscriptionWithLoadBalancing === 'function';
    const hasFallbackFunction = typeof window.fetchGeminiTranscriptionWithFallback === 'function';
    const hasBasicFunction = typeof window.fetchGeminiTranscription === 'function';

    if (!hasLoadBalancing && !hasFallbackFunction && !hasBasicFunction) {
      console.error('[YouTubeSubs] 🤖 Gemini: Module not loaded');
      return null;
    }

    const videoUrl = `https://www.youtube.com/watch?v=${videoId}`;

    if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] 🤖 Gemini: Requesting transcription...', forcePromptType ? `(force: ${forcePromptType})` : '', preferredKeyIndex !== null ? `(key index: ${preferredKeyIndex})` : '');

    // 🚀 Use load balancing if available and preferredKeyIndex is provided
    let result;
    if (hasLoadBalancing && hasMultiKeys && preferredKeyIndex !== null) {
      result = await window.fetchGeminiTranscriptionWithLoadBalancing(videoUrl, forcePromptType, translationLanguage, preferredKeyIndex);
    } else if (hasFallbackFunction) {
      result = await window.fetchGeminiTranscriptionWithFallback(videoUrl, forcePromptType, translationLanguage);
    } else {
      // Fallback to basic function (backward compatibility)
      result = await window.fetchGeminiTranscription(videoUrl, settings.geminiApiKey, forcePromptType, translationLanguage);
    }

    if (!result.success) {
      console.warn('[YouTubeSubs] 🤖 Gemini: Failed -', result.error);

      // 🎯 Show error modal to user
      if (typeof window.showGeminiErrorModal === 'function') {
        const errorType = determineGeminiErrorType(result.error);
        window.showGeminiErrorModal({
          type: errorType,
          message: result.error,
          onRetry: () => {
            // Retry by reloading subtitles
            if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] 🤖 Gemini: User requested retry');
            // The user can click the subtitle button again to retry
          }
        });
      }

      return null;
    }

    if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] 🤖 Gemini: Success! Got', result.subtitles.length, 'lines');

    // 🎯 Return full result object (including isCustomPrompt, isTranslation, rawResponse, and promptId)
    return {
      subtitles: result.subtitles,
      isCustomPrompt: result.isCustomPrompt || false,
      isTranslation: result.isTranslation || false, // 🆕
      rawResponse: result.rawResponse || null,
      promptId: result.promptId || null // 🎯 Include prompt ID
    };

  } catch (error) {
    console.error('[YouTubeSubs] 🤖 Gemini: Error -', error);

    // 🎯 Show error modal for unexpected errors
    if (typeof window.showGeminiErrorModal === 'function') {
      window.showGeminiErrorModal({
        type: 'generic',
        message: `Transcription failed: ${error.message}`
      });
    }

    return null;
  }
}

