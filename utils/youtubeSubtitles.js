function formatTime(seconds) {
  const hours = Math.floor(seconds / 3600);
  const minutes = Math.floor((seconds % 3600) / 60);
  const secs = Math.floor(seconds % 60);
  const milliseconds = Math.floor((seconds % 1) * 1000);
  return `${hours.toString().padStart(2, '0')}:${minutes.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')},${milliseconds.toString().padStart(3, '0')}`;
}

function cleanPunctuationSpacing(text) {
  return text.replace(/ +([,.!?;:])/g, '$1');
}

function countSubtitleWords(text) {
  return (String(text || '').trim().match(/\S+/g) || []).length;
}

function isSubtitleWithinHighlightLimits(text) {
  const normalizedText = String(text || '').trim();
  return (
    normalizedText.length <= MAX_LENGTH &&
    countSubtitleWords(normalizedText) <= MAX_WORDS_PER_HIGHLIGHT
  );
}

function canMergeSubtitleText(firstText, secondText) {
  const combinedText = `${firstText || ''} ${secondText || ''}`.trim();
  return isSubtitleWithinHighlightLimits(combinedText);
}

/**
 * ניקוי טקסט מתגיות וסימנים מיוחדים
 * @param {string} text - הטקסט לניקוי
 * @returns {string} - הטקסט המנוקה (או null אם צריך לסנן לגמרי)
 */
function cleanWordText(text) {
  if (!text) return null;

  let cleaned = text.trim();

  // הסרת חצים בתחילת המילה (>> או >)
  cleaned = cleaned.replace(/^>+\s*/, '');

  // הסרת סימני מוזיקה
  cleaned = cleaned.replace(/♪/g, '').replace(/♫/g, '');

  // אם מה שנשאר הוא רק תגית בסוגריים - סנן לגמרי
  if (/^\[.*\]$/.test(cleaned) || /^\(.*\)$/.test(cleaned)) {
    return null;
  }

  // הסרת תגיות בסוגריים מתוך הטקסט
  cleaned = cleaned.replace(/\[.*?\]/g, '').replace(/\(.*?\)/g, '');

  // ניקוי רווחים כפולים
  cleaned = cleaned.replace(/\s+/g, ' ').trim();

  // אם נשאר ריק - סנן
  if (!cleaned) return null;

  return cleaned;
}

/**
 * בדיקה אם מילה צריכה להיות מסוננת לגמרי
 */
function shouldFilterWord(text) {
  if (!text) return true;

  const cleaned = cleanWordText(text);
  if (!cleaned) return true;

  const t = cleaned.toLowerCase();

  // סינון מילים ספציפיות
  if (t === 'music' || t === 'applause' || t === 'laughter' || t === 'silence') return true;

  return false;
}

