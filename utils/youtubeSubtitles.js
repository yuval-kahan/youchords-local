const CAPTIONS_CACHE = new Map();
const CACHE_DURATION = 30000; // 30 שניות
const MAX_RETRIES = 2; // מקסימום ניסיונות נוספים (סה"כ 3)
const MAX_CACHE_SIZE = 10; // 🎯 מקסימום entries ב-cache למניעת דליפת זיכרון

/**
 * 🧹 ניקוי entries ישנים מה-cache
 * נקרא אוטומטית לפני הוספת entry חדש
 * 🎯 Optimized: Direct deletion without creating intermediate arrays
 */
function cleanupExpiredCache() {
  const now = Date.now();
  let deleted = 0;

  // מחק entries שפג תוקפם
  for (const [videoId, data] of CAPTIONS_CACHE.entries()) {
    if (now - data.timestamp > CACHE_DURATION) {
      CAPTIONS_CACHE.delete(videoId);
      deleted++;
    }
  }

  // אם עדיין יש יותר מדי - מחק את הישנים ביותר
  if (CAPTIONS_CACHE.size > MAX_CACHE_SIZE) {
    const toDelete = CAPTIONS_CACHE.size - MAX_CACHE_SIZE;

    // 🎯 Find and delete oldest entries without sorting entire array
    for (let i = 0; i < toDelete; i++) {
      let oldestId = null;
      let oldestTime = Infinity;

      for (const [videoId, data] of CAPTIONS_CACHE.entries()) {
        if (data.timestamp < oldestTime) {
          oldestTime = data.timestamp;
          oldestId = videoId;
        }
      }

      if (oldestId) {
        CAPTIONS_CACHE.delete(oldestId);
        deleted++;
      }
    }
  }

  if (DEBUG && deleted > 0) {
    console.log(`[YouTubeSubs] 🧹 Cleaned ${deleted} expired cache entries`);
  }
}

function setCaptionsCache(videoId, data) {
  cleanupExpiredCache();
  CAPTIONS_CACHE.set(videoId, { data, timestamp: Date.now() });
}

async function getAvailableCaptions(videoId) {
  if (!videoId) {
    const urlParams = new URLSearchParams(window.location.search);
    videoId = urlParams.get('v');
  }

  if (!videoId) return [];

  // 🎯 בדיקה ב-Cache
  const cached = CAPTIONS_CACHE.get(videoId);
  if (cached && Date.now() - cached.timestamp < CACHE_DURATION) {
    if (DEBUG_YOUTUBE_SUBS) console.log(`[YouTubeSubs] 💾 Cache hit for ${videoId}`);
    return cached.data;
  }

  if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] Getting captions for:', videoId);

  // ⏳ המתנה קצרה לפני הניסיון הראשון (נותן ליוטיוב זמן להכין את הדף)
  await new Promise(resolve => setTimeout(resolve, 1000));

  // 🎯 Optimized: Use loop instead of recursion to prevent stack overflow
  for (let attempt = 0; attempt <= MAX_RETRIES; attempt++) {
    try {
      const response = await fetch('https://www.youtube.com/youtubei/v1/player?prettyPrint=false', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          videoId,
          context: {
            // Current fix is intentionally minimal: updating the Android client version restored captions.
            // If YouTube tightens this again, we tested two fallback options:
            // 1) add Android context fields (androidSdkVersion/osName/osVersion/clientFormFactor/platform)
            // 2) use cookie-free caption fetches with credentials: 'omit' for player/json3 requests.
            client: { clientName: 'ANDROID', clientVersion: '20.15.37', hl: 'en', gl: 'US' }
          }
        })
      });

      if (!response.ok) throw new Error(`HTTP ${response.status}`);

      const data = await response.json();

      // 🐛 DEBUG: הדפסת התשובה המלאה
      if (DEBUG_YOUTUBE_SUBS) {
        console.log('%c[🐛 YouTubeSubs DEBUG] Full API Response:', 'color:#00FF00; font-weight:bold');
        console.log('%c[🐛 YouTubeSubs DEBUG] Response keys:', 'color:#00FF00', Object.keys(data));
        console.log('%c[🐛 YouTubeSubs DEBUG] Has captions key?', 'color:#00FF00', 'captions' in data);
        console.log('%c[🐛 YouTubeSubs DEBUG] captions value:', 'color:#00FF00', data.captions);
        console.log('%c[🐛 YouTubeSubs DEBUG] Full data object:', 'color:#00FF00', data);
      }

      // 🎯 הלוגיקה החכמה: בדיקת קיום המפתח captions
      if (!data.captions) {
        // המפתח חסר -> זה כנראה Skeleton Response
        if (attempt < MAX_RETRIES) {
          console.warn(`[YouTubeSubs] ⚠️ 'captions' key missing (attempt ${attempt + 1}/${MAX_RETRIES + 1}). Retrying...`);

          // חימום קצר לפני ניסיון חוזר (חשוב!)
          await new Promise(resolve => setTimeout(resolve, 800));
          continue; // 🎯 Continue loop instead of recursion
        } else {
          // ניסינו מספיק פעמים, כנראה שבאמת אין כתוביות
          console.log('[YouTubeSubs] ❌ No captions found after retries.');
          setCaptionsCache(videoId, []);
          return [];
        }
      }

      // המפתח קיים - בוא נבדוק אם יש מסלולים (tracks)
      const tracks = data.captions?.playerCaptionsTracklistRenderer?.captionTracks;

      if (DEBUG_YOUTUBE_SUBS) {
        console.log('%c[🐛 YouTubeSubs DEBUG] Checking tracks:', 'color:#00FF00; font-weight:bold');
        console.log('%c[🐛 YouTubeSubs DEBUG] playerCaptionsTracklistRenderer exists?', 'color:#00FF00', !!data.captions?.playerCaptionsTracklistRenderer);
        console.log('%c[🐛 YouTubeSubs DEBUG] captionTracks exists?', 'color:#00FF00', !!tracks);
        console.log('%c[🐛 YouTubeSubs DEBUG] captionTracks length:', 'color:#00FF00', tracks?.length || 0);
        console.log('%c[🐛 YouTubeSubs DEBUG] captionTracks data:', 'color:#00FF00', tracks);
      }

      if (!tracks || tracks.length === 0) {
        if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] ⚠️ Captions key exists but no tracks found.');
        setCaptionsCache(videoId, []);
        return [];
      }

      if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] ✅ Found', tracks.length, 'tracks');

      const parsedTracks = tracks.map(track => ({
        languageCode: track.languageCode,
        languageName: track.name?.simpleText || track.languageCode,
        baseUrl: track.baseUrl,
        isAutoGenerated: track.kind === 'asr',
        isDefault: track.isDefault || false
      }));

      // שמירה ב-Cache להבא
      setCaptionsCache(videoId, parsedTracks);

      return parsedTracks;

    } catch (error) {
      console.error('[YouTubeSubs] ❌ Error:', error);
      // במקרה של שגיאת רשת ממשית, אם זה הניסיון האחרון - החזר ריק
      if (attempt === MAX_RETRIES) {
        return [];
      }
      // אחרת המשך ללולאה הבאה
    }
  }

  // אם הגענו לכאן, כל הניסיונות נכשלו
  return [];
}


/**
 * מוריד כתוביות וממיר לרשימת מילים (כמו ElevenLabs)
 */
async function fetchWordsFromYouTube(videoId, languageCode = null, isAutoGenerated = null) {
  const captions = await getAvailableCaptions(videoId);

  if (captions.length === 0) {
    return { words: [], hasWordLevel: false };
  }

  let selected;

  if (languageCode) {
    // אם ביקשו שפה ספציפית - נסה למצוא אותה
    if (isAutoGenerated !== null) {
      // 🎯 חיפוש לפי קוד שפה וגם isAutoGenerated
      selected = captions.find(c => c.languageCode === languageCode && c.isAutoGenerated === isAutoGenerated);
    }
    if (!selected) {
      // fallback - חיפוש רק לפי קוד שפה
      selected = captions.find(c => c.languageCode === languageCode);
    }
    if (!selected) {
      if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] Requested language not found:', languageCode);
      // אם לא נמצאה - השתמש באלגוריתם החכם
      const videoTitle = getVideoTitle();
      const videoLanguage = detectLanguageFromTitle(videoTitle);
      selected = await selectBestCaption(captions, videoLanguage);
    }
  } else {
    // בחירה אוטומטית חכמה
    const videoTitle = getVideoTitle();
    const videoLanguage = detectLanguageFromTitle(videoTitle);
    if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] Video title:', videoTitle);
    if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] Detected video language:', videoLanguage);
    selected = await selectBestCaption(captions, videoLanguage);
  }

  // 🎯 עדכון השפה הנוכחית ב-window לסנכרון עם ה-UI
  window.currentSubtitleLanguage = selected.languageCode;
  window.currentSubtitleIsAutoGenerated = selected.isAutoGenerated || false;

  if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] Fetching:', selected.languageName, '- Updated currentSubtitleLanguage to:', selected.languageCode);

  try {
    const url = new URL(selected.baseUrl);
    url.searchParams.set('fmt', 'json3');

    const response = await fetch(url.toString(), { credentials: 'include' });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);

    const text = await response.text();
    if (!text) throw new Error('Empty response');

    const data = JSON.parse(text);

    // המרה לפורמט מילים (כמו ElevenLabs)
    const words = [];

    for (const event of (data.events || [])) {
      if (!event.segs) continue;

      const eventStartMs = event.tStartMs || 0;
      const eventDurationMs = event.dDurationMs || 3000;

      for (const seg of event.segs) {
        const rawText = (seg.utf8 || '').trim();
        if (!rawText) continue;

        // ניקוי הטקסט מתגיות וסימנים
        const wordText = cleanWordText(rawText);
        if (!wordText || shouldFilterWord(rawText)) continue;

        const startMs = eventStartMs + (seg.tOffsetMs || 0);
        // זמן סיום - נחשב לפי הסגמנט הבא או סוף האירוע
        const endMs = startMs + 500; // ברירת מחדל, יתוקן אח"כ

        words.push({
          type: 'word',
          text: wordText,  // שימוש בטקסט המנוקה
          start: startMs / 1000,  // המרה לשניות
          end: endMs / 1000
        });
      }
    }

    // תיקון זמני סיום - כל מילה מסתיימת כשהבאה מתחילה
    for (let i = 0; i < words.length - 1; i++) {
      const nextStart = words[i + 1].start;
      if (nextStart > words[i].start) {
        words[i].end = Math.min(nextStart, words[i].start + MAX_WORD_DURATION);
      }
    }

    // המילה האחרונה
    if (words.length > 0) {
      const last = words[words.length - 1];
      if (last.end - last.start > MAX_WORD_DURATION) {
        last.end = last.start + MAX_WORD_DURATION;
      }
    }

    const hasWordLevel = words.length > 0 && data.events?.some(e =>
      e.segs?.length > 1 && e.segs.some(s => s.tOffsetMs !== undefined)
    );

    // 🎯 יצירת מערך משפטים מקוריים מיוטיוב (לפני עיבוד)
    const originalSentences = [];
    for (const event of (data.events || [])) {
      if (!event.segs) continue;

      const startTime = (event.tStartMs || 0) / 1000;
      const endTime = startTime + ((event.dDurationMs || 3000) / 1000);

      // חיבור כל הסגמנטים לטקסט אחד
      const text = event.segs
        .map(seg => (seg.utf8 || '').trim())
        .filter(t => t)
        .join(' ')  // 🎯 תיקון: הוספת רווח בין הסגמנטים
        .trim();

      if (text) {
        originalSentences.push({
          text,
          startTime,
          endTime
        });
      }
    }

    if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] Extracted', words.length, 'words, hasWordLevel:', hasWordLevel, 'originalSentences:', originalSentences.length);

    return {
      words,
      hasWordLevel,
      originalSentences,
      languageCode: selected.languageCode,
      languageName: selected.languageName,
      isAutoGenerated: selected.isAutoGenerated || false
    };

  } catch (error) {
    console.error('[YouTubeSubs] Fetch error:', error);
    return { words: [], hasWordLevel: false };
  }
}

function originalSentencesToSRT(sentences) {
  const validSentences = Array.isArray(sentences) ? sentences : [];
  return validSentences
    .map((sentence, index) => {
      const start = Number(sentence?.startTime);
      const end = Number(sentence?.endTime);
      const text = String(sentence?.text || '').replace(/\r?\n/g, ' ').trim();
      if (!Number.isFinite(start) || !Number.isFinite(end) || end <= start || !text) {
        return '';
      }
      return `${index + 1}\n${formatTime(start)} --> ${formatTime(end)}\n${text}\n`;
    })
    .filter(Boolean)
    .join('\n');
}

async function fetchCaptionTrackAsSrt(videoId, languageCode, isAutoGenerated = null) {
  const result = await fetchWordsFromYouTube(videoId, languageCode, isAutoGenerated);
  if (!result?.words?.length && !result?.originalSentences?.length) {
    throw new Error('The selected YouTube subtitle track could not be downloaded');
  }

  let srt = originalSentencesToSRT(result.originalSentences);
  let originalSentences = result.originalSentences || [];
  if (!srt) {
    const generated = createSentenceSRT(result.words || []);
    srt = generated.srt;
    originalSentences = generated.originalSentences || [];
  }
  if (!srt.trim()) {
    throw new Error('The selected YouTube subtitle track is empty');
  }

  return {
    srt,
    originalSentences,
    languageCode: result.languageCode || languageCode || 'auto',
    languageName: result.languageName || languageCode || 'YouTube subtitles',
    isAutoGenerated: result.isAutoGenerated === true,
  };
}


