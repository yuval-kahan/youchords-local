/**
 * זיהוי שפה לטינית לפי מילים נפוצות
 */
function detectLatinLanguageFromWords(title) {
  const lowerTitle = title.toLowerCase();
  const words = lowerTitle.split(/\s+/);

  // ספירת התאמות
  let spanishScore = 0;
  let portugueseScore = 0;
  let frenchScore = 0;
  let germanScore = 0;
  let italianScore = 0;

  for (const word of words) {
    // הסרת סימני פיסוק מהמילה
    const cleanWord = word.replace(/[.,!?;:'"()]/g, '');
    if (cleanWord.length < 2) continue;

    // 🎯 Using Set.has() - O(1) instead of Array.includes() - O(n)
    if (SPANISH_WORDS.has(cleanWord)) spanishScore++;
    if (PORTUGUESE_WORDS.has(cleanWord)) portugueseScore++;
    if (FRENCH_WORDS.has(cleanWord)) frenchScore++;
    if (GERMAN_WORDS.has(cleanWord)) germanScore++;
    if (ITALIAN_WORDS.has(cleanWord)) italianScore++;
  }

  // בדיקת תווים מיוחדים
  if (title.includes('ñ') || title.includes('¿') || title.includes('¡')) spanishScore += 3;
  if (title.includes('ã') || title.includes('õ') || title.includes('ç')) portugueseScore += 3;
  if (title.includes('ç') || title.includes('œ') || title.includes('æ')) frenchScore += 2;
  if (title.includes('ß') || title.includes('ü') || title.includes('ö') || title.includes('ä')) germanScore += 3;
  if (title.includes('ì') || title.includes('ò') || title.includes('ù')) italianScore += 2;

  const scores = [
    { lang: 'es', score: spanishScore },
    { lang: 'pt', score: portugueseScore },
    { lang: 'fr', score: frenchScore },
    { lang: 'de', score: germanScore },
    { lang: 'it', score: italianScore }
  ];

  const maxScore = scores.reduce((max, curr) => curr.score > max.score ? curr : max, { lang: null, score: 0 });

  // צריך לפחות 2 התאמות כדי להיות בטוחים
  if (maxScore.score >= 2) {
    return maxScore.lang;
  }

  return null;
}

/**
 * ספירת מילים בכתוביות (לבחירה בין וריאציות)
 */
async function countWordsInCaption(caption) {
  try {
    const url = new URL(caption.baseUrl);
    url.searchParams.set('fmt', 'json3');

    const response = await fetch(url.toString(), { credentials: 'include' });
    if (!response.ok) return 0;

    const data = await response.json();
    let wordCount = 0;

    for (const event of (data.events || [])) {
      if (!event.segs) continue;
      for (const seg of event.segs) {
        const text = (seg.utf8 || '').trim();
        if (text) {
          wordCount += (text.match(/\S+/g) || []).length;
        }
      }
    }

    return wordCount;
  } catch (error) {
    console.error('[YouTubeSubs] Error counting words:', error);
    return 0;
  }
}

/**
 * בחירת הכתוביות עם הכי הרבה מילים מתוך רשימה
 * 🎯 Optimized: Run all fetches in parallel instead of sequentially
 */
async function selectCaptionWithMostWords(captions) {
  if (captions.length === 1) return captions[0];

  if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] Comparing', captions.length, 'captions by word count...');

  // 🎯 Run all word counts in parallel for better performance
  const wordCounts = await Promise.all(
    captions.map(caption => countWordsInCaption(caption))
  );

  let bestIndex = 0;
  let maxWords = wordCounts[0];

  for (let i = 1; i < wordCounts.length; i++) {
    if (DEBUG_YOUTUBE_SUBS) console.log(`[YouTubeSubs]   - ${captions[i].languageName}: ${wordCounts[i]} words`);

    if (wordCounts[i] > maxWords) {
      maxWords = wordCounts[i];
      bestIndex = i;
    }
  }

  if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] Selected:', captions[bestIndex].languageName, 'with', maxWords, 'words');
  return captions[bestIndex];
}

/**
 * Prefer human-created captions, then use word count only inside the same type.
 */
async function selectBestCaptionVariant(captions, label = 'captions') {
  if (!captions || captions.length === 0) return null;
  if (captions.length === 1) return captions[0];

  const manualCaptions = captions.filter(c => !c.isAutoGenerated);
  const autoCaptions = captions.filter(c => c.isAutoGenerated);
  const preferredGroup = manualCaptions.length > 0 ? manualCaptions : autoCaptions;

  if (DEBUG_YOUTUBE_SUBS) {
    console.log(
      `[YouTubeSubs] Multiple ${label}: manual=${manualCaptions.length}, auto=${autoCaptions.length}. ` +
      `Selecting ${manualCaptions.length > 0 ? 'manual' : 'auto'} variant by word count.`
    );
  }

  return await selectCaptionWithMostWords(preferredGroup);
}

/**
 * מיפוי קודי שפה ישנים לחדשים (YouTube משתמש בקודים ישנים)
 */
const LANGUAGE_CODE_ALIASES = {
  'he': ['he', 'iw'],      // עברית: he (חדש) ו-iw (ישן)
  'id': ['id', 'in'],      // אינדונזית: id (חדש) ו-in (ישן)
  'yi': ['yi', 'ji'],      // יידיש
  'jv': ['jv', 'jw'],      // ג'אוונית
};

/**
 * בדיקה אם קוד שפה של כתובית מתאים לשפה שזיהינו
 */
function languageCodeMatches(captionLangCode, detectedLang) {
  if (!captionLangCode || !detectedLang) return false;

  const captionBase = captionLangCode.split('-')[0].toLowerCase();
  const detectedBase = detectedLang.split('-')[0].toLowerCase();

  // בדיקה ישירה
  if (captionBase === detectedBase) return true;

  // בדיקה עם aliases
  const aliases = LANGUAGE_CODE_ALIASES[detectedBase];
  if (aliases && aliases.includes(captionBase)) return true;

  return false;
}

/**
 * בחירת שפת כתוביות חכמה
 * אלגוריתם:
 * 1. אם הכותרת מעורבת (אנגלית + שפה אחרת) → העדף את השפה האחרת
 * 2. אם הכותרת באנגלית → חפש אנגלית, אם יש כמה וריאציות → בחר את זו עם יותר מילים
 * 3. אם הכותרת בשפה אחרת → חפש את השפה הזו, אם אין → אנגלית AUTO, אם אין → כל שפה
 */
async function selectBestCaption(captions, videoLanguage) {
  if (!captions || captions.length === 0) return null;
  if (captions.length === 1) return captions[0];

  // זיהוי אם שפת הסרטון היא אנגלית
  const isEnglishVideo = !videoLanguage || videoLanguage.startsWith('en');

  // מציאת כל הכתוביות באנגלית
  const englishCaptions = captions.filter(c => c.languageCode.startsWith('en'));

  // מציאת כתוביות בשפת הסרטון (אם לא אנגלית) - עם תמיכה ב-aliases
  const videoLangCaptions = videoLanguage && !isEnglishVideo
    ? captions.filter(c => languageCodeMatches(c.languageCode, videoLanguage))
    : [];

  if (DEBUG_YOUTUBE_SUBS) {
    console.log('[YouTubeSubs] Smart selection - isEnglishVideo:', isEnglishVideo);
    console.log('[YouTubeSubs] English captions:', englishCaptions.length);
    console.log('[YouTubeSubs] Video language captions:', videoLangCaptions.length);
  }

  // אם הסרטון לא באנגלית ויש כתוביות בשפת הסרטון
  if (!isEnglishVideo && videoLangCaptions.length > 0) {
    if (videoLangCaptions.length === 1) {
      if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] Selected video language caption:', videoLangCaptions[0].languageName);
      return videoLangCaptions[0];
    }
    // יש כמה וריאציות - העדף ידניות, ואז בחר לפי מספר מילים
    return await selectBestCaptionVariant(videoLangCaptions, 'video-language captions');
  }

  // סרטון באנגלית או אין כתוביות בשפת הסרטון - חפש אנגלית
  if (englishCaptions.length > 0) {
    if (englishCaptions.length === 1) {
      if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] Selected English caption:', englishCaptions[0].languageName);
      return englishCaptions[0];
    }
    // יש כמה וריאציות אנגלית - העדף ידניות, ואז בחר לפי מספר מילים
    return await selectBestCaptionVariant(englishCaptions, 'English captions');
  }

  // אין שפה מזוהה/אנגלית - העדף default אם יש
  const defaultCaption = captions.find(c => c.isDefault);
  if (defaultCaption) {
    if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] Selected default caption:', defaultCaption.languageName);
    return defaultCaption;
  }

  // אין default - העדף כתובית ידנית כלשהי, ואם אין אז auto-generated, לפי כמות מילים
  const fallbackCaption = await selectBestCaptionVariant(captions, 'fallback captions');
  if (fallbackCaption) {
    if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] Selected fallback caption:', fallbackCaption.languageName);
    return fallbackCaption;
  }

  if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] Selected first available caption:', captions[0].languageName);
  return captions[0];
}

