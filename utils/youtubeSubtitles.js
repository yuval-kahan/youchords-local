function createWordSRT(modifiedWords) {
  let srt = '';
  let index = 1;

  for (const word of modifiedWords) {
    if (word.type !== 'word') continue;

    const startTime = word.start;
    const endTime = word.end;
    const text = word.text || '';

    if (!text.trim()) continue;

    srt += `${index}\n${formatTime(startTime)} --> ${formatTime(endTime)}\n${text}\n\n`;
    index++;
  }

  return srt;
}


