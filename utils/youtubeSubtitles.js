async function buildGeminiRequestFingerprint(videoId, languageCode, isAutoGenerated, options = {}) {
  try {
    const aiSettings = await chrome.storage.local.get([
      'aiTranscriptionMode',
      'geminiApiKey',
      'geminiApiKeys',
      PROMPT_DISCLAIMER_KEY,
      'alwaysAllowYoutubeFallback'
    ]);

    const aiMode = normalizeAiMode(aiSettings.aiTranscriptionMode);
    const hasApiKey = !!aiSettings.geminiApiKey || hasActiveGeminiMultiKey(aiSettings.geminiApiKeys);
    const promptDisclaimerAccepted = aiSettings[PROMPT_DISCLAIMER_KEY] === true;

    // We only dedupe requests that can trigger Gemini API calls.
    if (!hasApiKey || !promptDisclaimerAccepted || (aiMode !== 'always' && aiMode !== 'auto')) {
      return null;
    }

    const promptSettings = await chrome.storage.local.get([
      'showDefault',
      'selectedCustomPromptId',
      'selectedPromptId',
      'showTranslation',
      'translationLanguage',
      'translationIncludeOriginal',
      'translationSecondaryLanguage'
    ]);

    let showDefault = promptSettings.showDefault;
    let selectedCustomPromptId = promptSettings.selectedCustomPromptId;

    // Backward compatibility with older selectedPromptId storage format.
    if (showDefault === undefined && promptSettings.selectedPromptId) {
      if (promptSettings.selectedPromptId === 'default') {
        showDefault = true;
        selectedCustomPromptId = null;
      } else {
        showDefault = false;
        selectedCustomPromptId = promptSettings.selectedPromptId;
      }
    }

    if (showDefault === undefined) showDefault = true;
    if (selectedCustomPromptId === undefined) selectedCustomPromptId = null;

    const showTranslation = !!promptSettings.showTranslation;
    const translationLanguage = promptSettings.translationLanguage || 'he';
    const translationIncludeOriginal = !!promptSettings.translationIncludeOriginal;
    const translationSecondaryLanguage = promptSettings.translationSecondaryLanguage || null;

    const ignoreCustom = !!options.ignoreCustom || !!options.ignoreCustomPrompts;
    const needCustom = ignoreCustom ? false : !!selectedCustomPromptId;

    const fingerprint = {
      videoId,
      aiMode,
      allowYoutubeFallbackInAlways: aiSettings.alwaysAllowYoutubeFallback !== false,
      languageCode: languageCode || null,
      isAutoGenerated: typeof isAutoGenerated === 'boolean' ? isAutoGenerated : null,
      needDefault: !!showDefault,
      needTranslation: showTranslation,
      translationLanguage: showTranslation ? translationLanguage : null,
      translationIncludeOriginal: showTranslation ? translationIncludeOriginal : false,
      translationSecondaryLanguage: showTranslation ? translationSecondaryLanguage : null,
      needCustom,
      selectedCustomPromptId: needCustom ? selectedCustomPromptId : null
    };

    return stableStringify(fingerprint);
  } catch (error) {
    console.warn('[YouTubeSubs] Failed to build Gemini request fingerprint:', error);
    return null;
  }
}

