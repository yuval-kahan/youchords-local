const MAX_LENGTH = 41;              // Short highlight unit for panel/carousel
const MAX_WORDS_PER_HIGHLIGHT = 6;  // Keep word-level YouTube highlights readable
const MAX_TIME_GAP = 0.5;           // פער זמני מקסימלי למיזוג
const MAX_SENTENCES = 2;            // מקסימום משפטים בכתובית
const MAX_FIRST_WORD_DURATION = 1.5; // משך מקסימלי למילה ראשונה
const MAX_LAST_WORD_DURATION = 1.5;  // משך מקסימלי למילה אחרונה
const MAX_WORD_DURATION = 1.5;       // משך מקסימלי למילה

