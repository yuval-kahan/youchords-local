/**
 * מביא את כותרת הסרטון מיוטיוב
 */
function getVideoTitle() {
  // אופציה 1: מ-ytInitialPlayerResponse (הכי אמין)
  if (window.ytInitialPlayerResponse?.videoDetails?.title) {
    return window.ytInitialPlayerResponse.videoDetails.title;
  }

  // אופציה 2: מה-DOM
  const titleElement = document.querySelector('h1.ytd-video-primary-info-renderer') ||
    document.querySelector('yt-formatted-string.ytd-video-primary-info-renderer') ||
    document.querySelector('#title h1');
  if (titleElement?.textContent) {
    return titleElement.textContent.trim();
  }

  return null;
}

/**
 * זיהוי שפה מהכותרת לפי תווים ומילים נפוצות
 * מחזיר קוד שפה (he, ar, ko, ja, zh, ru, th, es, pt, fr, de, it, en) או null
 */
function detectLanguageFromTitle(title) {
  if (!title) return null;

  // ספירת תווים לפי סוג
  let hebrewCount = 0;
  let arabicCount = 0;
  let koreanCount = 0;
  let japaneseCount = 0;
  let chineseCount = 0;
  let cyrillicCount = 0;
  let thaiCount = 0;
  let latinCount = 0;

  for (const char of title) {
    const code = char.charCodeAt(0);

    // עברית: U+0590 - U+05FF
    if (code >= 0x0590 && code <= 0x05FF) hebrewCount++;
    // ערבית: U+0600 - U+06FF
    else if (code >= 0x0600 && code <= 0x06FF) arabicCount++;
    // קוריאנית: U+AC00 - U+D7AF (Hangul Syllables)
    else if (code >= 0xAC00 && code <= 0xD7AF) koreanCount++;
    // יפנית: Hiragana U+3040-U+309F, Katakana U+30A0-U+30FF
    else if ((code >= 0x3040 && code <= 0x309F) || (code >= 0x30A0 && code <= 0x30FF)) japaneseCount++;
    // סינית: U+4E00 - U+9FFF (CJK Unified Ideographs)
    else if (code >= 0x4E00 && code <= 0x9FFF) chineseCount++;
    // קירילית (רוסית): U+0400 - U+04FF
    else if (code >= 0x0400 && code <= 0x04FF) cyrillicCount++;
    // תאית: U+0E00 - U+0E7F
    else if (code >= 0x0E00 && code <= 0x0E7F) thaiCount++;
    // לטינית: a-z, A-Z
    else if ((code >= 0x0041 && code <= 0x005A) || (code >= 0x0061 && code <= 0x007A)) latinCount++;
  }

  // מציאת השפה הדומיננטית (לא-לטינית)
  const nonLatinCounts = [
    { lang: 'he', count: hebrewCount },
    { lang: 'ar', count: arabicCount },
    { lang: 'ko', count: koreanCount },
    { lang: 'ja', count: japaneseCount },
    { lang: 'zh', count: chineseCount },
    { lang: 'ru', count: cyrillicCount },
    { lang: 'th', count: thaiCount }
  ];

  const maxNonLatin = nonLatinCounts.reduce((max, curr) => curr.count > max.count ? curr : max, { lang: null, count: 0 });

  // אם יש תווים לא-לטיניים - העדף אותם (גם אם יש אנגלית)
  if (maxNonLatin.count > 0) {
    if (DEBUG_YOUTUBE_SUBS) console.log(`[YouTubeSubs] Detected language from title: ${maxNonLatin.lang} (${maxNonLatin.count} chars)`);
    return maxNonLatin.lang;
  }

  // אם רק לטינית - נסה לזהות שפה לפי מילים נפוצות
  if (latinCount > 0) {
    const detectedLatin = detectLatinLanguageFromWords(title);
    if (detectedLatin) {
      if (DEBUG_YOUTUBE_SUBS) console.log(`[YouTubeSubs] Detected language from words: ${detectedLatin}`);
      return detectedLatin;
    }
    if (DEBUG_YOUTUBE_SUBS) console.log('[YouTubeSubs] Detected language from title: en (Latin, no specific language detected)');
    return 'en';
  }

  return null;
}

