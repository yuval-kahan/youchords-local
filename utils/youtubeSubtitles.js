// ============================================================================

function createSentenceSRT(words) {
  if (!words || words.length === 0) return { srt: '', modifiedWords: [] };

  // 🎯 Optimized: Use shallow copy (slice) instead of deep copy (map)
  // Only create new objects when we actually modify them
  const modifiedWords = words.slice();

  // הגבלת משך המילה האחרונה
  let lastWordIndex = null;
  for (let i = modifiedWords.length - 1; i >= 0; i--) {
    if (modifiedWords[i].type === 'word') {
      lastWordIndex = i;
      break;
    }
  }

  if (lastWordIndex !== null) {
    const lastWord = modifiedWords[lastWordIndex];
    const duration = lastWord.end - lastWord.start;
    if (duration > MAX_LAST_WORD_DURATION) {
      // 🎯 Create copy only when modifying
      modifiedWords[lastWordIndex] = { ...lastWord, end: lastWord.start + MAX_LAST_WORD_DURATION };
    }
  }

  const subtitles = [];
  let sentenceWords = [];
  let currentText = '';
  let wordIndices = [];

  const pushCurrentSubtitle = (isSentenceEnd = false, excludeLastWord = false) => {
    const activeWords = excludeLastWord ? sentenceWords.slice(0, -1) : sentenceWords;
    const activeIndices = excludeLastWord ? wordIndices.slice(0, -1) : wordIndices;
    const text = currentText.trim();

    if (!text || activeWords.length === 0) return;

    const firstWord = activeWords[0];
    const firstWordIndex = activeIndices[0];
    let startTime = firstWord.start;

    if (firstWord.end - firstWord.start > MAX_FIRST_WORD_DURATION) {
      startTime = firstWord.end - MAX_FIRST_WORD_DURATION;
      modifiedWords[firstWordIndex] = { ...firstWord, start: startTime };
    }

    const lastWord = activeWords[activeWords.length - 1];
    const lastWordIndex = activeIndices[activeIndices.length - 1];
    let endTime = lastWord.end;

    if (lastWord.end - lastWord.start > MAX_LAST_WORD_DURATION) {
      endTime = lastWord.start + MAX_LAST_WORD_DURATION;
      modifiedWords[lastWordIndex] = { ...lastWord, end: endTime };
    }

    subtitles.push({
      index: subtitles.length + 1,
      startTime,
      endTime,
      text,
      isSentenceEnd,
      wordIndices: [...activeIndices]
    });
  };

  for (let i = 0; i < modifiedWords.length; i++) {
    const word = modifiedWords[i];
    if (word.type !== 'word') continue;

    const previousWord = sentenceWords[sentenceWords.length - 1];
    if (
      currentText.trim() &&
      previousWord &&
      word.start - previousWord.end > MAX_TIME_GAP
    ) {
      pushCurrentSubtitle(false);
      currentText = '';
      sentenceWords = [];
      wordIndices = [];
    }

    sentenceWords.push(word);
    wordIndices.push(i);
    const wordText = word.text || '';
    // הוספת רווח בין מילים
    const testText = currentText ? currentText + ' ' + wordText : wordText;

    // אם חורג מאורך/מספר מילים מקסימלי - סגור כתובית
    if (
      currentText &&
      (testText.trim().length > MAX_LENGTH || sentenceWords.length > MAX_WORDS_PER_HIGHLIGHT)
    ) {
      pushCurrentSubtitle(false, true);
      currentText = wordText;
      sentenceWords = [word];
      wordIndices = [i];
    } else {
      currentText = testText;
    }

    // אם מסתיים בנקודה - סגור משפט
    if (wordText.endsWith('.') || wordText.endsWith('!') || wordText.endsWith('?')) {
      pushCurrentSubtitle(true);
      currentText = '';
      sentenceWords = [];
      wordIndices = [];
    }
  }

  // אם נשאר טקסט - הוסף אותו
  if (currentText.trim() && sentenceWords.length > 0) {
    pushCurrentSubtitle(false);
  }

  // מיזוג כתוביות קצרות (כמו בשרת)
  const mergedSubtitles = mergeShortSubtitles(subtitles);

  // יצירת SRT
  let srt = '';
  for (const sub of mergedSubtitles) {
    const cleanText = cleanPunctuationSpacing(sub.text);
    srt += `${sub.index}\n${formatTime(sub.startTime)} --> ${formatTime(sub.endTime)}\n${cleanText}\n\n`;
  }

  const originalSentences = mergedSubtitles.map((sub) => ({
    text: cleanPunctuationSpacing(sub.text),
    startTime: sub.startTime,
    endTime: sub.endTime
  }));

  return { srt, modifiedWords, originalSentences };
}


/**
 * מיזוג כתוביות קצרות (כמו בשרת)
 */
function mergeShortSubtitles(subtitles) {
  if (subtitles.length === 0) return [];

  // זיהוי כתוביות עם מילה אחת
  const singleWordIndices = [];
  for (let i = 0; i < subtitles.length; i++) {
    const wordCount = countSubtitleWords(subtitles[i].text);
    if (wordCount <= 1) {
      singleWordIndices.push(i);
    }
  }

  const merged = [];
  const skipIndices = new Set();

  // מיזוג כתוביות עם מילה אחת
  for (const idx of singleWordIndices) {
    if (skipIndices.has(idx)) continue;

    const current = subtitles[idx];
    let wasMerged = false;

    // נסה למזג עם הקודם
    if (idx > 0 && !skipIndices.has(idx - 1)) {
      const prev = subtitles[idx - 1];
      const timeGap = current.startTime - prev.endTime;

      if (timeGap <= MAX_TIME_GAP && canMergeSubtitleText(prev.text, current.text)) {
        const combinedText = prev.text + ' ' + current.text;
        merged.push({
          index: prev.index,
          startTime: prev.startTime,
          endTime: current.endTime,
          text: combinedText.trim(),
          wordIndices: [...(prev.wordIndices || []), ...(current.wordIndices || [])]
        });
        skipIndices.add(idx);
        skipIndices.add(idx - 1);
        wasMerged = true;
      }
    }

    // אם לא מוזג עם הקודם, נסה עם הבא
    if (!wasMerged && idx < subtitles.length - 1 && !skipIndices.has(idx + 1)) {
      const next = subtitles[idx + 1];
      const timeGap = next.startTime - current.endTime;

      if (timeGap <= MAX_TIME_GAP && canMergeSubtitleText(current.text, next.text)) {
        const combinedText = current.text + ' ' + next.text;
        merged.push({
          index: current.index,
          startTime: current.startTime,
          endTime: next.endTime,
          text: combinedText.trim(),
          wordIndices: [...(current.wordIndices || []), ...(next.wordIndices || [])]
        });
        skipIndices.add(idx);
        skipIndices.add(idx + 1);
      }
    }
  }

  // הוסף את השאר
  for (let i = 0; i < subtitles.length; i++) {
    if (skipIndices.has(i)) continue;

    const current = subtitles[i];
    let combinedText = current.text;
    let startTime = current.startTime;
    let endTime = current.endTime;
    let sentenceCount = current.isSentenceEnd ? 1 : 0;
    let combinedWordIndices = [...(current.wordIndices || [])];

    let nextIndex = i + 1;
    while (nextIndex < subtitles.length) {
      if (skipIndices.has(nextIndex)) {
        nextIndex++;
        continue;
      }

      const next = subtitles[nextIndex];
      const timeGap = next.startTime - endTime;

      if (timeGap > MAX_TIME_GAP) break;
      if (next.isSentenceEnd && sentenceCount >= MAX_SENTENCES) break;

      const potentialText = combinedText + ' ' + next.text;
      if (isSubtitleWithinHighlightLimits(potentialText)) {
        combinedText = potentialText;
        endTime = next.endTime;
        combinedWordIndices.push(...(next.wordIndices || []));
        if (next.isSentenceEnd) sentenceCount++;
        skipIndices.add(nextIndex);
        nextIndex++;
      } else {
        break;
      }
    }

    merged.push({
      index: current.index,
      startTime,
      endTime,
      text: combinedText.trim(),
      wordIndices: combinedWordIndices
    });
  }

  // מיון לפי זמן
  merged.sort((a, b) => a.startTime - b.startTime);

  // עדכון אינדקסים
  merged.forEach((sub, i) => sub.index = i + 1);

  return merged;
}

