/**
 * Execute async functions with concurrency limit
 * @param {Array} tasks - Array of {type, execute} objects
 * @param {number} limit - Max concurrent executions
 * @returns {Promise<Array>} Results in same order as tasks
 */
async function executeWithConcurrencyLimit(tasks, limit) {
  const results = new Array(tasks.length);
  const allPromises = []; // 🔧 Track ALL promises to wait for them at the end
  
  for (let i = 0; i < tasks.length; i++) {
    const task = tasks[i];
    const promise = task.execute().then(result => {
      results[i] = result;
      return result;
    });
    
    allPromises.push(promise); // 🔧 Add to allPromises for final wait
    
    // If we've reached the limit, wait for one to finish before starting next
    if (allPromises.length >= limit && i < tasks.length - 1) {
      await Promise.race(allPromises);
    }
  }
  
  // 🔧 Wait for ALL promises to complete (not just the ones in executing)
  await Promise.all(allPromises);
  
  return results;
}

