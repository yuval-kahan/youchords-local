/**
 * 🎯 Delete cached custom-prompt response from subtitles record
 * Used when user wants to force-regenerate a specific custom prompt (e.g. about-song language change)
 */
async function deleteCustomPromptResponse(videoId, promptId = null) {
  console.log(
    `[DatabaseManager] Deleting custom prompt cache for ${videoId}${
      promptId ? ` (prompt: ${promptId})` : ""
    }`
  );

  const cfg = DB_CONFIG.subtitles;
  if (!cfg) throw new Error("Subtitles DB config not found");

  const db = await openDatabase("subtitles");
  const os = withStore(db, cfg.store, "readwrite");
  const hashedId = hashVideoId(videoId);

  return new Promise((res, rej) => {
    const getReq = os.get(hashedId);

    getReq.onsuccess = () => {
      const record = getReq.result;

      if (!record) {
        console.log(`[DatabaseManager] No subtitles record found for ${videoId}`);
        res({ deleted: false, reason: "record_not_found" });
        return;
      }

      const cachedPromptId = record[FIELD_MAP.customPromptId] || null;

      if (promptId && cachedPromptId && cachedPromptId !== promptId) {
        console.log(
          `[DatabaseManager] Custom cache belongs to different prompt (${cachedPromptId}), skip delete`
        );
        res({
          deleted: false,
          reason: "prompt_mismatch",
          cachedPromptId,
        });
        return;
      }

      const hadCustomResponse = record[FIELD_MAP.customPromptResponse] != null;

      delete record[FIELD_MAP.customPromptResponse];
      delete record[FIELD_MAP.customPromptId];
      delete record[FIELD_MAP.isCustomPrompt];

      const putReq = os.put(record);
      putReq.onsuccess = () => {
        console.log(`[DatabaseManager] Deleted custom prompt cache for ${videoId}`);
        res({
          deleted: hadCustomResponse,
          reason: hadCustomResponse ? "deleted" : "already_empty",
        });
      };
      putReq.onerror = (e) => rej(e.target.error);
    };

    getReq.onerror = (e) => rej(e.target.error);
  });
}

