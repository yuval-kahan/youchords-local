// Simple XOR encryption key (obfuscated)
const ENC_KEY = 0x5A; // Simple key for XOR

// Simple hash function for videoId obfuscation
function hashVideoId(videoId) {
  if (!videoId) return videoId;
  let hash = 0;
  for (let i = 0; i < videoId.length; i++) {
    const char = videoId.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash; // Convert to 32bit integer
  }
  // Convert to hex and make it look random
  return Math.abs(hash).toString(36).substring(0, 12);
}

// Encode string to Base64 with XOR
function encodeData(str) {
  if (!str) return str;
  try {
    // Convert string to UTF-8 bytes
    const encoder = new TextEncoder();
    const bytes = encoder.encode(str);

    // XOR each byte
    const xored = new Uint8Array(bytes.length);
    for (let i = 0; i < bytes.length; i++) {
      xored[i] = bytes[i] ^ ENC_KEY;
    }

    // Convert to binary string for btoa
    let binaryString = '';
    for (let i = 0; i < xored.length; i++) {
      binaryString += String.fromCharCode(xored[i]);
    }

    // Base64 encode
    return btoa(binaryString);
  } catch (e) {
    console.error('[DB] Encode error:', e);
    return str;
  }
}

// Decode Base64 with XOR
function decodeData(str) {
  if (!str) return str;
  try {
    // Base64 decode to binary string
    const binaryString = atob(str);

    // Convert binary string to bytes
    const bytes = new Uint8Array(binaryString.length);
    for (let i = 0; i < binaryString.length; i++) {
      bytes[i] = binaryString.charCodeAt(i);
    }

    // XOR each byte back
    const xored = new Uint8Array(bytes.length);
    for (let i = 0; i < bytes.length; i++) {
      xored[i] = bytes[i] ^ ENC_KEY;
    }

    // Convert bytes to UTF-8 string
    const decoder = new TextDecoder();
    return decoder.decode(xored);
  } catch (e) {
    console.error('[DB] Decode error:', e);
    return str;
  }
}

