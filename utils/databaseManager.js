function withStore(db, store, mode) {
  const tx = db.transaction(store, mode);
  const os = tx.objectStore(store);
  const end = () => {
    try {
      db.close();
    } catch { }
  };
  tx.oncomplete = end;
  tx.onerror = end;
  return os;
}

