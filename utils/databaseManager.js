/*–– 3. פתיחת DB + טיפול ב-upgrade ––––––––––––––––––––––––––––––––––––––*/
function openDatabase(dbType) {
  return new Promise((resolve, reject) => {
    const cfg = DB_CONFIG[dbType];
    if (!cfg) return reject(new Error(`Unknown DB type: ${dbType}`));

    const req = indexedDB.open(cfg.name, cfg.version);

    req.onerror = (e) => reject(e.target.error);

    req.onupgradeneeded = (e) => {
      const db = e.target.result;
      const storeName = cfg.store;

      /* –– מחיקת Store ישן ויצירת חדש (clean slate) –– */
      if (db.objectStoreNames.contains(storeName))
        db.deleteObjectStore(storeName);
      const os = db.createObjectStore(storeName, { keyPath: FIELD_MAP.id }); // 'i' instead of 'id'

      if (dbType === "subtitles") {
        // אינדקסים לכתוביות (obfuscated field names)
        [
          FIELD_MAP.sentenceSRT,
          FIELD_MAP.geminiSentenceSRT,
          FIELD_MAP.wordSRT,
          FIELD_MAP.translationSRT,
          FIELD_MAP.translationOriginalSentences,
          FIELD_MAP.source,
          FIELD_MAP.lastUpdated
        ].forEach((i) =>
          os.createIndex(i, i, { unique: false })
        );
      } else if (dbType === "chords") {
        // אינדקסים לאקורדים (obfuscated field names)
        [FIELD_MAP.chordText, FIELD_MAP.tuningValue, FIELD_MAP.source, FIELD_MAP.lastUpdated].forEach((i) =>
          os.createIndex(i, i, { unique: false })
        );
      } else if (dbType === "guitar") {
        db.shouldInitGuitar = true;
      } else if (dbType === "globalPositions") {
        db.shouldInitGlobalPositions = true;
      }
    };

    req.onsuccess = async (e) => {
      const db = e.target.result;
      track(db);
      if (
        dbType === "guitar" &&
        db.shouldInitGuitar &&
        window.COMPLETE_CHORDS
      ) {
        delete db.shouldInitGuitar;
        await initializeGuitarChordsDatabase(db);
      }
      if (dbType === "globalPositions" && db.shouldInitGlobalPositions) {
        delete db.shouldInitGlobalPositions;
        await initializeGlobalPositionsDatabase(db);
      }
      resolve(db);
    };
  });
}

