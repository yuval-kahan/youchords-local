const SUBTITLE_OFFSET_MIN = -6;
const SUBTITLE_OFFSET_MAX = 6;
const SUBTITLE_OFFSET_STEP = 0.1;

function clampSubtitleOffset(value) {
  const num = Number(value);
  if (!Number.isFinite(num)) return 0;
  const clamped = Math.min(SUBTITLE_OFFSET_MAX, Math.max(SUBTITLE_OFFSET_MIN, num));
  return Math.round(clamped / SUBTITLE_OFFSET_STEP) * SUBTITLE_OFFSET_STEP;
}

function normalizeSubtitleOffsetsBySource(rawMap) {
  const normalized = {
    [SUBTITLE_OFFSET_SOURCE_KEYS.YOUTUBE_DEFAULT]: 0,
    [SUBTITLE_OFFSET_SOURCE_KEYS.GEMINI_DEFAULT]: 0,
    [SUBTITLE_OFFSET_SOURCE_KEYS.GEMINI_TRANSLATION]: 0,
    [SUBTITLE_OFFSET_SOURCE_KEYS.WHISPER_DEFAULT]: 0,
    [SUBTITLE_OFFSET_SOURCE_KEYS.CUSTOM]: 0,
  };

  if (!rawMap || typeof rawMap !== "object") {
    return normalized;
  }

  for (const key of Object.keys(normalized)) {
    if (Object.prototype.hasOwnProperty.call(rawMap, key)) {
      normalized[key] = clampSubtitleOffset(rawMap[key]);
    }
  }

  return normalized;
}

function resolveSubtitleOffsetSourceKey({ useTranslation = false, activeDefaultSource = "youtube" } = {}) {
  if (activeDefaultSource === "custom") {
    return SUBTITLE_OFFSET_SOURCE_KEYS.CUSTOM;
  }

  if (useTranslation) {
    return SUBTITLE_OFFSET_SOURCE_KEYS.GEMINI_TRANSLATION;
  }

  if (activeDefaultSource === "whisper") {
    return SUBTITLE_OFFSET_SOURCE_KEYS.WHISPER_DEFAULT;
  }

  return activeDefaultSource === "gemini"
    ? SUBTITLE_OFFSET_SOURCE_KEYS.GEMINI_DEFAULT
    : SUBTITLE_OFFSET_SOURCE_KEYS.YOUTUBE_DEFAULT;
}

