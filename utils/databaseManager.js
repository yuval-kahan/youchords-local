// Obfuscate record (encode field names and encrypt values)
function obfuscateRecord(record, dbType) {
  const obfuscated = {};
  for (const [key, value] of Object.entries(record)) {
    const obfKey = FIELD_MAP[key] || key;

    // 🔐 Hash the videoId (id field)
    if (key === 'id' && typeof value === 'string') {
      obfuscated[obfKey] = hashVideoId(value);
    }
    // Encrypt string fields
    else if (ENCRYPTED_FIELDS.has(key) && typeof value === 'string') {
      obfuscated[obfKey] = encodeData(value);
    }
    // Encrypt objects and arrays (convert to JSON, then encrypt)
    else if (value !== null && typeof value === 'object') {
      obfuscated[obfKey] = encodeData(JSON.stringify(value));
    }
    // Keep primitives as-is (numbers, booleans, nulls)
    else {
      obfuscated[obfKey] = value;
    }
  }
  return obfuscated;
}

// Deobfuscate record (decode field names and decrypt values)
function deobfuscateRecord(record, dbType) {
  if (!record) return null;
  const deobfuscated = {};
  for (const [obfKey, value] of Object.entries(record)) {
    const key = FIELD_MAP_REVERSE[obfKey] || obfKey;

    // 🔓 Decrypt only fields that are in ENCRYPTED_FIELDS
    if (ENCRYPTED_FIELDS.has(key) && typeof value === 'string') {
      const decoded = decodeData(value);

      // 🆕 Parse JSON for array/object fields (translationOriginalSentences, originalSentences)
      if (
        key === 'translationOriginalSentences' ||
        key === 'originalSentences' ||
        key === 'geminiOriginalSentences' ||
        key === 'customSubtitleOriginalSentences'
        || key === 'wordTranslations'
      ) {
        try {
          deobfuscated[key] = JSON.parse(decoded);
        } catch (e) {
          console.warn(`[DB] Failed to parse ${key} as JSON, keeping as string:`, e);
          deobfuscated[key] = decoded;  // Fallback to string
        }
      } else {
        deobfuscated[key] = decoded;
      }
    }
    // 🔓 Try to decrypt and parse objects/arrays (only if they look encrypted)
    else if (typeof value === 'string' && value.length > 0 && isBase64(value)) {
      try {
        const decrypted = decodeData(value);
        // Try to parse as JSON (if it's an encrypted object)
        deobfuscated[key] = JSON.parse(decrypted);
      } catch (e) {
        // If parsing fails, keep as regular string
        deobfuscated[key] = value;
      }
    }
    // ✅ Keep all other values as-is (including non-encrypted strings)
    else {
      deobfuscated[key] = value;
    }
  }
  return deobfuscated;
}

// Helper function to check if string looks like Base64
function isBase64(str) {
  if (!str || str.length === 0) return false;
  // Base64 only contains: A-Z, a-z, 0-9, +, /, =
  const base64Regex = /^[A-Za-z0-9+/]+=*$/;
  return base64Regex.test(str);
}

