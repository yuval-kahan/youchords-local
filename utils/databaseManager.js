/*–– 12. Storage Quota Management — Evict Oldest Records ––––––––––––––––*/
/**
 * Evict oldest records from a DB when storage is full.
 * Deletes the oldest `percentage`% of records (sorted by lastUpdated).
 * Only applicable to chords and subtitles DBs.
 * @param {string} dbType - 'chords' or 'subtitles'
 * @param {number} percentage - Percentage of records to delete (default 50)
 * @returns {Promise<{deletedCount: number, remainingCount: number}>}
 */
async function evictOldRecords(dbType, percentage = 50) {
  if (dbType !== 'chords' && dbType !== 'subtitles') {
    console.warn(`[DatabaseManager] 🧹 Eviction skipped for ${dbType} (not applicable)`);
    return { deletedCount: 0, remainingCount: 0 };
  }

  console.log(`[DatabaseManager] 🧹 Evicting oldest ${percentage}% from ${dbType}...`);
  const cfg = DB_CONFIG[dbType];
  const db = await openDatabase(dbType);

  return new Promise((resolve, reject) => {
    // Phase 1: Read all records and sort by lastUpdated
    const readTx = db.transaction(cfg.store, 'readonly');
    const readStore = readTx.objectStore(cfg.store);
    const getAllReq = readStore.getAll();

    getAllReq.onsuccess = () => {
      const allRecords = getAllReq.result || [];
      const totalCount = allRecords.length;

      if (totalCount === 0) {
        try { db.close(); } catch { }
        resolve({ deletedCount: 0, remainingCount: 0 });
        return;
      }

      // Sort by lastUpdated ascending (oldest first)
      // Field 'u' is the obfuscated lastUpdated field
      allRecords.sort((a, b) => (a[FIELD_MAP.lastUpdated] || 0) - (b[FIELD_MAP.lastUpdated] || 0));

      const deleteCount = Math.ceil(totalCount * (percentage / 100));
      const keysToDelete = allRecords.slice(0, deleteCount).map(r => r[FIELD_MAP.id]);

      console.log(`[DatabaseManager] 🧹 Deleting ${deleteCount}/${totalCount} records from ${dbType}`);

      // Phase 2: Delete oldest records in a new transaction
      const deleteTx = db.transaction(cfg.store, 'readwrite');
      const deleteStore = deleteTx.objectStore(cfg.store);

      keysToDelete.forEach(key => deleteStore.delete(key));

      deleteTx.oncomplete = () => {
        try { db.close(); } catch { }
        const remaining = totalCount - deleteCount;
        console.log(`[DatabaseManager] 🧹 Eviction complete: ${deleteCount} deleted, ${remaining} remaining`);
        resolve({ deletedCount: deleteCount, remainingCount: remaining });
      };

      deleteTx.onerror = (e) => {
        try { db.close(); } catch { }
        console.error(`[DatabaseManager] 🧹 Eviction delete failed:`, e.target.error);
        reject(e.target.error);
      };
    };

    getAllReq.onerror = (e) => {
      try { db.close(); } catch { }
      console.error(`[DatabaseManager] 🧹 Eviction read failed:`, e.target.error);
      reject(e.target.error);
    };
  });
}

/*–– 13. Premium Data Cleanup (for downgrade from Pro+) ––––––––––––––––––*/
/**
 * מוחק נתונים פרימיום מכל השירים ב-IndexedDB
 * נקרא כשמשתמש עושה downgrade מ-Pro+ ל-Pro/Free
 * @returns {Promise<{success: boolean, count: number}>}
 */
async function clearPremiumDataFromAllSongs() {
  console.log('[DatabaseManager] 🔒 Starting premium data cleanup...');

  try {
    const cfg = DB_CONFIG.chords;
    const db = await openDatabase('chords');

    return new Promise((resolve, reject) => {
      const tx = db.transaction(cfg.store, 'readwrite');
      const store = tx.objectStore(cfg.store);
      const request = store.openCursor();

      let updatedCount = 0;

      request.onsuccess = (event) => {
        const cursor = event.target.result;
        if (cursor) {
          const obfuscatedRecord = cursor.value;
          // 🔑 Save the original obfuscated ID (hash) to prevent key mismatch
          const originalObfuscatedId = obfuscatedRecord.i;

          // 🔐 Deobfuscate to check and modify
          const record = deobfuscateRecord(obfuscatedRecord, 'chords');
          let needsUpdate = false;

          // בדיקה אם יש נתונים פרימיום למחוק
          if (record.capoChords) {
            record.capoChords = null;
            needsUpdate = true;
          }
          if (record.chordTextHarmonic) {
            record.chordTextHarmonic = null;
            needsUpdate = true;
          }
          if (record.chordTextHarmonicPlus) {
            record.chordTextHarmonicPlus = null;
            needsUpdate = true;
          }
          if (record.tuningValue) {
            record.tuningValue = null;
            needsUpdate = true;
          }

          if (needsUpdate) {
            record.lastUpdated = Date.now();
            // 🔐 Re-obfuscate before updating
            const updatedObfuscated = obfuscateRecord(record, 'chords');
            // 🔑 CRITICAL: Restore the original obfuscated ID to prevent key mismatch error
            updatedObfuscated.i = originalObfuscatedId;
            cursor.update(updatedObfuscated);
            updatedCount++;
            console.log(`[DatabaseManager] 🔒 Cleaned premium data from: ${record.id}`);
          }

          cursor.continue();
        }
      };

      tx.oncomplete = () => {
        try { db.close(); } catch { }
        console.log(`[DatabaseManager] 🔒 Premium data cleanup complete. Updated ${updatedCount} songs.`);
        resolve({ success: true, count: updatedCount });
      };

      tx.onerror = (e) => {
        try { db.close(); } catch { }
        console.error('[DatabaseManager] 🔒 Premium data cleanup failed:', e.target.error);
        reject(e.target.error);
      };
    });
  } catch (error) {
    console.error('[DatabaseManager] 🔒 Premium data cleanup error:', error);
    return { success: false, count: 0 };
  }
}

/*–– 14. Grace Period & DB Deletion Management ––––––––––––––––––––––––––*/
const GRACE_PERIOD_KEY = 'yc_subscription_expired_at';
const GRACE_PERIOD_HOURS = 24;

/**
 * Delete Chords Database completely
 * Called when subscription expires or account is deleted
 */
async function deleteChordsDatabase() {
  try {
    console.log('[DB] 🗑️ Deleting Chords Database...');

    // Delete the obfuscated database (using the name from DB_CONFIG)
    const chordsDBName = DB_CONFIG.chords.name; // "ycdb_7a3f9e2b"

    await new Promise((resolve, reject) => {
      const request = indexedDB.deleteDatabase(chordsDBName);
      request.onsuccess = () => {
        console.log('[DB] ✅ Chords Database deleted successfully');
        resolve();
      };
      request.onerror = () => {
        console.error('[DB] ❌ Failed to delete Chords Database:', request.error);
        reject(request.error);
      };
      request.onblocked = () => {
        console.warn('[DB] ⚠️ Chords Database deletion blocked - close all tabs');
      };
    });

    // Clear grace period timestamp
    localStorage.removeItem(GRACE_PERIOD_KEY);

    return { success: true };
  } catch (error) {
    console.error('[DB] Error deleting Chords Database:', error);
    return { success: false, error: error.message };
  }
}

/**
 * Check if grace period has expired (24 hours)
 * Returns true if DB should be deleted
 */
function shouldDeleteChordsDB() {
  const expiredAt = localStorage.getItem(GRACE_PERIOD_KEY);

  if (!expiredAt) {
    return false; // No grace period set
  }

  const hoursPassed = (Date.now() - parseInt(expiredAt)) / (1000 * 60 * 60);

  if (hoursPassed >= GRACE_PERIOD_HOURS) {
    console.log(`[DB] ⏰ Grace period expired (${hoursPassed.toFixed(1)} hours passed)`);
    return true;
  }

  console.log(`[DB] ⏰ Grace period active (${(GRACE_PERIOD_HOURS - hoursPassed).toFixed(1)} hours remaining)`);
  return false;
}

/**
 * Start grace period when subscription expires
 * Called when Pro → Free transition is detected
 */
function startGracePeriod() {
  const now = Date.now();
  localStorage.setItem(GRACE_PERIOD_KEY, now.toString());
  console.log(`[DB] ⏰ Grace period started - DB will be deleted in ${GRACE_PERIOD_HOURS} hours`);
}

/**
 * Check and delete DB if grace period expired
 * Called on extension load and periodically
 */
async function checkAndDeleteExpiredData() {
  if (shouldDeleteChordsDB()) {
    console.log('[DB] 🗑️ Grace period expired - deleting Chords Database');
    await deleteChordsDatabase();
  }
}

