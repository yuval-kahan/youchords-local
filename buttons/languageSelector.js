// languageSelector.js - Language Selector Component
// כפתור בחירת שפה לכתוביות - משותף לפאנל ולקרוסלה

(function (window) {
  "use strict";

  const DEBUG = false;

  // 🎯 מיפוי קודי שפה ישנים לחדשים (להצגה ב-UI)
  const OLD_TO_NEW_LANG_CODE = {
    'iw': 'he',  // עברית
    'in': 'id',  // אינדונזית
    'ji': 'yi',  // יידיש
    'jw': 'jv',  // ג'אוונית
  };

  // 🎯 המרת קוד שפה להצגה (iw -> he)
  function getDisplayLangCode(langCode) {
    if (!langCode) return langCode;
    const base = langCode.split('-')[0].toLowerCase();
    return OLD_TO_NEW_LANG_CODE[base] || base;
  }

  // 🌐 פונקציה לטעינת רשימת השפות הזמינות
  async function getAvailableLanguages() {
    try {
      const videoId = window.ycUtils?.extractVideoId(window.location.href);
      if (!videoId) return [];

      let availableLanguages = [];

      if (window.youtubeSubtitles && typeof window.youtubeSubtitles.getAvailableCaptions === "function") {
        DEBUG && console.log("[LanguageSelector] 🌐 Calling getAvailableCaptions...");
        const captions = await window.youtubeSubtitles.getAvailableCaptions(videoId);
        
        if (captions && Array.isArray(captions)) {
          availableLanguages = captions.map(c => ({
            code: c.languageCode,
            name: c.languageName || c.name || c.languageCode,
            isAutoGenerated: c.isAutoGenerated || false
          }));
        }
      }

      DEBUG && console.log("[LanguageSelector] 🌐 Available languages:", availableLanguages);
      return availableLanguages;
    } catch (error) {
      console.error("[LanguageSelector] Error getting languages:", error);
      return [];
    }
  }

  // 🌐 פונקציה להחלפת שפת כתוביות
  async function switchLanguage(langCode, isAutoGenerated = false) {
    try {
      const videoId = window.ycUtils?.extractVideoId(window.location.href);
      if (!videoId) return false;

      console.log("[LanguageSelector] 🌐 Switching to language:", langCode, "isAuto:", isAutoGenerated);

      // שמירת השפה הנוכחית
      window.currentSubtitleLanguage = langCode;
      window.currentSubtitleIsAutoGenerated = isAutoGenerated;

      // טעינת כתוביות בשפה החדשה
      if (window.extractorModule && typeof window.extractorModule.extractSubtitlesFromTarGz === "function") {
        // מחיקת הכתוביות הישנות מ-IndexedDB
        if (window.databaseManager?.deleteFromDatabase) {
          await window.databaseManager.deleteFromDatabase("subtitles", videoId);
        }

        // טעינת כתוביות חדשות - מעביר גם את isAutoGenerated
        await window.extractorModule.extractSubtitlesFromTarGz(videoId, langCode, isAutoGenerated);

        // שליחת event שהשפה השתנתה - הפאנל והקרוסלה יאזינו לזה
        window.dispatchEvent(new CustomEvent("yc:languageChanged", {
          detail: { langCode, videoId, isAutoGenerated }
        }));

        console.log("[LanguageSelector] 🌐 Language switched successfully to:", langCode);
        return true;
      }

      return false;
    } catch (error) {
      console.error("[LanguageSelector] Error switching language:", error);
      return false;
    }
  }

  // 🌐 פונקציה למילוי dropdown עם שפות
  // useInlineStyles: true לקרוסלה (סגנונות inline), false לפאנל (CSS classes)
  async function populateDropdown(dropdown, onSelect, useInlineStyles = false) {
    if (!dropdown) return;

    if (useInlineStyles) {
      dropdown.innerHTML = '<div style="padding: 8px 12px; color: #333;">Loading...</div>';
    } else {
      dropdown.innerHTML = '<div class="language-dropdown-item">Loading...</div>';
    }

    const languages = await getAvailableLanguages();

    if (!languages || languages.length === 0) {
      if (useInlineStyles) {
        dropdown.innerHTML = '<div style="padding: 8px 12px; color: #333;">No captions available</div>';
      } else {
        dropdown.innerHTML = '<div class="language-dropdown-item">No captions available</div>';
      }
      return;
    }

    dropdown.innerHTML = "";
    const currentLanguage = window.currentSubtitleLanguage || "en";
    const currentIsAuto = window.currentSubtitleIsAutoGenerated || false;

    languages.forEach(lang => {
      const item = document.createElement("div");
      item.className = "language-dropdown-item";
      // 🎯 השוואה גם לקוד השפה וגם ל-isAutoGenerated
      const isSelected = lang.code === currentLanguage && lang.isAutoGenerated === currentIsAuto;
      
      if (isSelected) {
        item.classList.add("selected");
      }

      // סגנונות inline רק לקרוסלה
      if (useInlineStyles) {
        Object.assign(item.style, {
          padding: "8px 12px",
          cursor: "pointer",
          borderBottom: "1px solid #eee",
          background: isSelected ? "#e3f2fd" : "#fff",
          fontWeight: isSelected ? "bold" : "normal",
          color: "#333",
          fontSize: "13px",
        });

        item.addEventListener("mouseenter", () => {
          item.style.background = "#f0f0f0";
        });
        item.addEventListener("mouseleave", () => {
          item.style.background = isSelected ? "#e3f2fd" : "#fff";
        });
      }
      
      item.textContent = `${lang.name} (${lang.code})`;
      item.dataset.langCode = lang.code;

      item.addEventListener("click", async (e) => {
        e.stopPropagation();
        e.preventDefault();
        
        console.log("[LanguageSelector] 🌐 Selected language:", lang.code);
        
        // סגירת ה-dropdown מיד
        dropdown.classList.remove("open");
        if (useInlineStyles) {
          dropdown.style.display = "none";
        }
        
        // עדכון הסימון של כל הפריטים
        dropdown.querySelectorAll(".language-dropdown-item").forEach(el => {
          el.classList.remove("selected");
          if (useInlineStyles) {
            el.style.background = "#fff";
            el.style.fontWeight = "normal";
          }
        });
        item.classList.add("selected");
        if (useInlineStyles) {
          item.style.background = "#e3f2fd";
          item.style.fontWeight = "bold";
        }
        
        await switchLanguage(lang.code, lang.isAutoGenerated);
        
        if (onSelect) {
          onSelect(lang.code);
        }
      });

      dropdown.appendChild(item);
    });

    console.log("[LanguageSelector] 🌐 Loaded", languages.length, "languages");
  }

  // 🌐 יצירת כפתור שפה לקרוסלה
  // שומר reference ל-listener לצורך cleanup
  let _documentClickHandler = null;

  async function initCarousel() {
    const wrapper = document.querySelector(".yc-root-wrapper");
    if (!wrapper) return null;

    // בדיקה אם כבר קיים
    if (wrapper.querySelector(".yc-language-container")) return null;

    // 🌐 בדיקה אם יש כתוביות זמינות - אם אין, לא מציגים את האייקון
    // 🎯 גם אם יש רק שפה אחת - אין טעם להציג בורר שפה
    const languages = await getAvailableLanguages();
    if (!languages || languages.length <= 1) {
      console.log("[LanguageSelector] 🌐 No captions or only one language - not showing language icon");
      return null;
    }

    // 🎯 קריאת השפה מ-IndexedDB אם לא מוגדרת ב-window
    let currentLang = window.currentSubtitleLanguage;
    let currentIsAuto = window.currentSubtitleIsAutoGenerated;
    
    if (!currentLang) {
      try {
        const videoId = window.ycUtils?.extractVideoId(window.location.href);
        if (videoId && window.databaseManager?.loadFromDatabase) {
          const subtitlesData = await window.databaseManager.loadFromDatabase("subtitles", videoId);
          if (subtitlesData?.languageCode) {
            currentLang = subtitlesData.languageCode;
            currentIsAuto = subtitlesData.isAutoGenerated || false;
            window.currentSubtitleLanguage = currentLang;
            window.currentSubtitleIsAutoGenerated = currentIsAuto;
            DEBUG && console.log("[LanguageSelector] 🌐 Loaded language from IndexedDB:", currentLang, "isAuto:", currentIsAuto);
          }
        }
      } catch (e) {
        DEBUG && console.log("[LanguageSelector] 🌐 Error loading language from IndexedDB:", e);
      }
    }
    
    // fallback לשפה הראשונה ברשימה
    if (!currentLang) {
      currentLang = languages[0]?.code || "en";
    }

    // Container - מוסתר כברירת מחדל, CSS יטפל בהצגה על hover
    const container = document.createElement("div");
    container.className = "yc-language-container";
    Object.assign(container.style, {
      position: "absolute",
      left: "95px", // מימין לקאפו עם קצת רווח
      top: "2px",
      display: "flex",
      alignItems: "center",
      gap: "2px",
      opacity: "0", // מוסתר כברירת מחדל - CSS יטפל בהצגה
      transition: "opacity 0.2s ease",
      zIndex: "100",
    });

    // קוד שפה (ללא גלובוס) - Subtle Style
    const langCode = document.createElement("div");
    langCode.className = "yc-language-code";
    langCode.textContent = getDisplayLangCode(currentLang).toUpperCase();
    Object.assign(langCode.style, {
      fontSize: "11px",
      fontWeight: "600",
      color: "#333",
      cursor: "pointer",
      padding: "4px 8px",
      borderRadius: "6px",
      background: "rgba(0,0,0,0.08)",
      border: "none",
      transition: "all 0.2s ease",
    });

    langCode.addEventListener("mouseenter", () => {
      langCode.style.background = "rgba(0,0,0,0.15)";
    });
    langCode.addEventListener("mouseleave", () => {
      langCode.style.background = "rgba(0,0,0,0.08)";
    });

    // Dropdown
    const dropdown = document.createElement("div");
    dropdown.className = "yc-language-dropdown";
    Object.assign(dropdown.style, {
      position: "absolute",
      top: "100%",
      left: "0",
      background: "#fff",
      border: "1px solid #ccc",
      borderRadius: "4px",
      boxShadow: "0 2px 8px rgba(0,0,0,0.15)",
      display: "none",
      minWidth: "180px",
      maxHeight: "250px",
      overflowY: "auto",
      zIndex: "1000",
    });

    // לחיצה על קוד השפה פותחת dropdown
    const toggleDropdown = async (e) => {
      e.stopPropagation();
      e.preventDefault();
      const isOpen = dropdown.style.display === "block";
      
      console.log("[LanguageSelector] 🌐 Toggle dropdown, isOpen:", isOpen);
      
      if (isOpen) {
        dropdown.style.display = "none";
      } else {
        await populateDropdown(dropdown, (newLangCode) => {
          langCode.textContent = getDisplayLangCode(newLangCode).toUpperCase();
          dropdown.style.display = "none";
        }, true); // useInlineStyles = true לקרוסלה
        dropdown.style.display = "block";
      }
    };

    langCode.addEventListener("click", toggleDropdown);

    // סגירה בלחיצה מחוץ - שומר reference לצורך cleanup
    // מסיר listener קודם אם קיים
    if (_documentClickHandler) {
      document.removeEventListener("click", _documentClickHandler);
    }
    _documentClickHandler = (e) => {
      if (!container.contains(e.target)) {
        dropdown.style.display = "none";
      }
    };
    document.addEventListener("click", _documentClickHandler);

    container.appendChild(langCode);
    container.appendChild(dropdown);
    wrapper.appendChild(container);

    // 🎯 האזנה לשינוי שפה - עדכון קוד השפה בקרוסלה
    const languageChangeHandler = (e) => {
      if (e.detail?.langCode) {
        langCode.textContent = getDisplayLangCode(e.detail.langCode).toUpperCase();
        console.log("[LanguageSelector] 🌐 Updated carousel language code to:", getDisplayLangCode(e.detail.langCode));
      }
    };
    window.addEventListener("yc:languageChanged", languageChangeHandler);
    
    // שמירת ה-handler לצורך cleanup
    container._languageChangeHandler = languageChangeHandler;

    console.log("[LanguageSelector] 🌐 Created for carousel");
    return container;
  }

  // 🌐 הסרת כפתור מהקרוסלה
  function cleanupCarousel() {
    // הסרת ה-document click listener
    if (_documentClickHandler) {
      document.removeEventListener("click", _documentClickHandler);
      _documentClickHandler = null;
    }
    
    const container = document.querySelector(".yc-language-container");
    if (container) {
      // 🎯 הסרת ה-language change listener
      if (container._languageChangeHandler) {
        window.removeEventListener("yc:languageChanged", container._languageChangeHandler);
      }
      container.remove();
      console.log("[LanguageSelector] 🌐 Removed from carousel");
    }
  }

  // חשיפה גלובלית
  window.LanguageSelector = {
    getAvailableLanguages,
    switchLanguage,
    populateDropdown,
    initCarousel,
    cleanupCarousel
  };

  console.log("[LanguageSelector] 🌐 Module loaded");

})(window);
